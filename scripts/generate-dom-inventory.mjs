import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const digest = bytes => createHash('sha256').update(bytes).digest('hex');
const outputs = [
  ['packages/kwdj/src/dom-inventory.ts', 'kwdj', true],
  ['examples/notes-extension/dom-inventory.mjs', 'notesD0', false],
];

/** Native build-time proof, never a frontend registry enumerator or own-build-ID input. */
export function generateDomInventory({ check = false, locked = true } = {}) {
  const result = spawnSync('cargo', ['run', ...(locked ? ['--locked'] : []), '--quiet',
    '-p', 'klenwriter-editor-wasm', '--example', 'dom_inventory'], {
    cwd: root, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`Native DOM inventory failed (${result.status}):\n${result.stderr}`);
  if (result.stderr) process.stderr.write(result.stderr);
  const native = JSON.parse(result.stdout);
  if (native.format !== 'klenwriter-editor-dom-inventory/1') throw new Error('Unknown DOM inventory format');
  const files = [];
  for (const [path, key, typed] of outputs) {
    const binding = native[key];
    if (!binding || !/^[a-f0-9]{64}$/.test(binding.registryDigest)) throw new Error('Invalid native DOM inventory');
    const source = '// SPDX-License-Identifier: MIT OR Apache-2.0\n'
      + '// Generated by scripts/generate-dom-inventory.mjs from public compiled registrations. Do not edit.\n'
      + `export const ${key}DomInventory = ${JSON.stringify(binding, null, 2)}${typed ? ' as const' : ''};\n`;
    const full = resolve(root, path);
    if (check) {
      if (!existsSync(full) || readFileSync(full, 'utf8') !== source) throw new Error(`Stale native DOM inventory: ${path}`);
    } else writeFileSync(full, source);
    files.push({ path, sha256: digest(source), bytes: Buffer.byteLength(source), registryDigest: binding.registryDigest });
  }
  mkdirSync(resolve(root, 'artifacts'), { recursive: true });
  writeFileSync(resolve(root, 'artifacts/dom-inventory.json'), JSON.stringify({
    format: native.format, source: 'public mandatory registrations resolved through FrozenRegistry',
    nativeOutputSha256: digest(result.stdout), files,
  }, null, 2) + '\n');
  return { format: native.format, files };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.some(arg => !['--check', '--resolve-lock'].includes(arg))) throw new Error('Usage: node scripts/generate-dom-inventory.mjs [--check] [--resolve-lock]');
  console.log(JSON.stringify(generateDomInventory({ check: args.includes('--check'), locked: !args.includes('--resolve-lock') })));
}
